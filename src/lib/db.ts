type Params = unknown[];

export interface Statement {
  get<T = Record<string, unknown>>(...params: Params): Promise<T | undefined>;
  all<T = Record<string, unknown>>(...params: Params): Promise<T[]>;
  /** For INSERT, UPDATE and DELETE: how many rows it changed. */
  run(...params: Params): Promise<{ changes: number }>;
}

export interface Database {
  prepare(sql: string): Statement;
  /** Several statements with no parameters. */
  exec(sql: string): Promise<void>;
}

/** SQL written with ? placeholders, numbered the way Postgres wants them ($1, $2…); quoted text is left alone. */
export function numbered(sql: string): string {
  let out = "";
  let n = 0;
  let quote: string | null = null;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (quote) {
      out += c;
      if (c === quote) quote = null;
    } else if (c === "'" || c === '"') {
      quote = c;
      out += c;
    } else if (c === "?") {
      out += `$${++n}`;
    } else {
      out += c;
    }
  }
  return out;
}

const TENANT_TABLE = new RegExp(`\\b(${TENANT_TABLES.join("|")})\\b`, "i");

interface Pools {
  app: pg.Pool;
  admin: pg.Pool;
  ready: Promise<void>;
  key: string;
}

const state = globalThis as unknown as { __keelPools?: Pools };

/** A connection address with another database name (a test's own database). */
const withDatabase = (url: string, name: string) => {
  const u = new URL(url);
  u.pathname = `/${name}`;
  return u.toString();
};

function addresses(): { app: string; admin: string; testDatabase?: string } {
  const app = setting("DATABASE_URL");
  if (!app) throw new Error("DATABASE_URL isn't set. Run `npm run db:setup` once, and add the addresses it prints to .env.local.");
  const admin = setting("DATABASE_ADMIN_URL") ?? app;
  const testDatabase = process.env.KEEL_TEST_DATABASE;
  // A test never touches the real database: each test file gets its own (src/testing/live.ts).
  if (process.env.NODE_TEST_CONTEXT && !testDatabase) throw new Error("A test reached the database without its own: call live() or offline() at the top of the test file.");
  return testDatabase ? { app: withDatabase(app, testDatabase), admin: withDatabase(admin, testDatabase), testDatabase } : { app, admin };
}

async function migrate(admin: pg.Pool, appUser: string): Promise<void> {
  const client = await admin.connect();
  try {
    // One migrator at a time, even with several processes starting together.
    await client.query("SELECT pg_advisory_lock(424242)");
    await client.query("CREATE TABLE IF NOT EXISTS migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)");
    const applied = new Set((await client.query<{ version: number }>("SELECT version FROM migrations")).rows.map((r) => r.version));
    for (const [i, sql] of MIGRATIONS.entries()) {
      const version = i + 1;
      if (applied.has(version)) continue;
      await client.query("BEGIN");
      try {
        await client.query(sql);
        await client.query("INSERT INTO migrations (version, applied_at) VALUES ($1, $2)", [version, new Date().toISOString()]);
        await client.query("COMMIT");
      } catch (error) {
        await client.query("ROLLBACK");
        throw error;
      }
    }
    // Keel's own login reads and writes the tables; it owns none of them, so row-level security holds for it.
    const owner = (await client.query<{ u: string }>("SELECT current_user AS u")).rows[0].u;
    if (appUser !== owner) {
      const role = pg.escapeIdentifier(appUser);
      await client.query(`GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ${role}; GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ${role}; GRANT EXECUTE ON FUNCTION keel_tenant() TO ${role};`);
    } else if (!process.env.NODE_TEST_CONTEXT) {
      console.warn("Keel connects to Postgres as the owner of its tables, so row-level security doesn't apply. Set DATABASE_URL to a separate login (npm run db:setup).");
    }
  } finally {
    await client.query("SELECT pg_advisory_unlock(424242)").catch(() => {});
    client.release();
  }
}

/** Creates a test's own database, from the owner login. */
async function createTestDatabase(adminUrl: string, name: string): Promise<void> {
  const client = new pg.Client({ connectionString: withDatabase(adminUrl, "postgres") });
  await client.connect();
  try {
    const exists = await client.query("SELECT 1 FROM pg_database WHERE datname = $1", [name]);
    if (!exists.rowCount) await client.query(`CREATE DATABASE ${pg.escapeIdentifier(name)}`);
  } finally {
    await client.end();
  }
}

function pools(): Pools {
  const { app, admin, testDatabase } = addresses();
  const key = `${app}|${admin}`;
  if (state.__keelPools?.key === key) return state.__keelPools;
  void state.__keelPools?.app.end().catch(() => {});
  void state.__keelPools?.admin.end().catch(() => {});
  const appPool = new pg.Pool({ connectionString: app, max: 10 });
  const adminPool = new pg.Pool({ connectionString: admin, max: 3 });
  // A dropped connection is replaced on the next query; it mustn't stop the server.
  appPool.on("error", () => {});
  adminPool.on("error", () => {});
  const appUser = decodeURIComponent(new URL(app).username);
  const ready = (async () => {
    if (testDatabase) await createTestDatabase(setting("DATABASE_ADMIN_URL") ?? setting("DATABASE_URL")!, testDatabase);
    await migrate(adminPool, appUser);
  })();
  ready.catch(() => {});
  state.__keelPools = { app: appPool, admin: adminPool, ready, key };
  return state.__keelPools;
}

type Tagged = pg.PoolClient & { keelTenant?: string };

/** The transaction the current work is inside, if any: queries in it go to its connection. */
const inTransaction = new AsyncLocalStorage<{ client: Tagged; depth: number; tenant: string }>();

/** Runs a query as Keel's own login, for the current business. */
async function appQuery(sql: string, params: Params): Promise<pg.QueryResult> {
  const tenant = await currentTenant();
  if (!tenant && TENANT_TABLE.test(sql)) {
    throw new Error(`Keel queried a business's data with no business set: ${sql.replace(/\s+/g, " ").slice(0, 120)}`);
  }
  const p = pools();
  await p.ready;
  const tx = inTransaction.getStore();
  if (tx) {
    // Work inside the transaction can be for another business (an invitation joins its workspace).
    if (tx.tenant !== (tenant ?? "")) {
      await tx.client.query("SELECT set_config('keel.workspace', $1, true)", [tenant ?? ""]);
      tx.tenant = tenant ?? "";
    }
    return tx.client.query(numbered(sql), params);
  }
  const client = (await p.app.connect()) as Tagged;
  try {
    // The business is kept with the connection, and set again only when it changes.
    if (client.keelTenant !== (tenant ?? "")) {
      await client.query("SELECT set_config('keel.workspace', $1, false)", [tenant ?? ""]);
      client.keelTenant = tenant ?? "";
    }
    return await client.query(numbered(sql), params);
  } finally {
    client.release();
  }
}

function databaseOf(run: (sql: string, params: Params) => Promise<pg.QueryResult>): Database {
  return {
    prepare: (sql) => ({
      get: async <T>(...params: Params) => (await run(sql, params)).rows[0] as T | undefined,
      all: async <T>(...params: Params) => (await run(sql, params)).rows as T[],
      run: async (...params: Params) => ({ changes: (await run(sql, params)).rowCount ?? 0 }),
    }),
    exec: async (sql) => {
      await run(sql, []);
    },
  };
}

const appDatabase = databaseOf(appQuery);

/** The database, for the business the current work is for. */
export function db(): Database {
  return appDatabase;
}

const systemDatabase = databaseOf(async (sql, params) => {
  const p = pools();
  await p.ready;
  return p.admin.query(numbered(sql), params);
});

/**
 * The database across every business, past row-level security. Only for what comes before a business is known (which
 * business an agent, conversation, invite or API key belongs to) and for Keel's own upkeep (migrations, recovery after
 * a restart); never to read or change a business's data for someone.
 */
export function system(): Database {
  return systemDatabase;
}

/**
 * Runs `work` in one transaction: all of it is saved, or none of it. Every query inside it (through db(), however deep)
 * goes to the transaction. Inside another transaction it's a savepoint, so a failure undoes only its own part.
 */
export async function transaction<T>(work: (database: Database) => Promise<T>): Promise<T> {
  const outer = inTransaction.getStore();
  if (outer) {
    const name = `sp_${outer.depth}`;
    await outer.client.query(`SAVEPOINT ${name}`);
    try {
      const result = await inTransaction.run(outer, async () => {
        outer.depth++;
        try {
          return await work(appDatabase);
        } finally {
          outer.depth--;
        }
      });
      await outer.client.query(`RELEASE SAVEPOINT ${name}`);
      return result;
    } catch (error) {
      await outer.client.query(`ROLLBACK TO SAVEPOINT ${name}; RELEASE SAVEPOINT ${name}`);
      throw error;
    }
  }
  const tenant = await currentTenant();
  const p = pools();
  await p.ready;
  const client = (await p.app.connect()) as Tagged;
  try {
    await client.query("BEGIN");
    // For this transaction only: the connection's own setting comes back when it ends.
    await client.query("SELECT set_config('keel.workspace', $1, true)", [tenant ?? ""]);
    const result = await inTransaction.run({ client, depth: 1, tenant: tenant ?? "" }, () => work(appDatabase));
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK").catch(() => {});
    throw error;
  } finally {
    client.release();
  }
}

/** Closes the connections; for a test, its own database is removed too. */
export async function closeDb(): Promise<void> {
  const p = state.__keelPools;
  if (!p) return;
  state.__keelPools = undefined;
  await p.ready.catch(() => {});
  await Promise.all([p.app.end(), p.admin.end()]).catch(() => {});
  const testDatabase = process.env.KEEL_TEST_DATABASE;
  if (testDatabase) {
    const admin = setting("DATABASE_ADMIN_URL") ?? setting("DATABASE_URL")!;
    const client = new pg.Client({ connectionString: withDatabase(admin, "postgres") });
    await client.connect();
    await client.query(`DROP DATABASE IF EXISTS ${pg.escapeIdentifier(testDatabase)} WITH (FORCE)`).catch(() => {});
    await client.end();
  }
}

/** A vector as stored: 32-bit floats. */
export const toBlob = (vector: number[] | Float32Array) => Buffer.from(Float32Array.from(vector).buffer);
export const fromBlob = (blob: Uint8Array) => {
  // A copy: the bytes needn't be aligned for 32-bit floats.
  const copy = blob.slice();
  return new Float32Array(copy.buffer, 0, copy.byteLength / 4);
};
