// Keel's database: Postgres. One database holds accounts and workspaces, the agents people build, their knowledge
// (sources and searchable chunks), conversations and everything around them. Schema changes are numbered migrations,
// applied once, in order, by the owner login (DATABASE_ADMIN_URL).
//
// Many businesses share it, and Postgres keeps them apart: every table of a business's data has a workspace_id, and
// row-level security shows and accepts only the rows of the business the current work is for (src/lib/tenant.ts).
// Keel itself connects with a login that can't get around it (DATABASE_URL). With no business set, those tables show
// nothing, and Keel refuses the query. The owner login is used only for migrations and for the few lookups that come
// before a business is known (which business an agent or an API key belongs to), through system().

